// 🧠 რა არის Virtual DOM?

// Virtual DOM არის React-ის „ვირტუალური ასლი“ რეალური DOM-ის.

// 👉 ანუ:

// რეალურ HTML-ს პირდაპირ არ ცვლის
// ჯერ ქმნის კოპიას (Virtual DOM)
// ადარებს ძველსა და ახალს
// მერე მხოლოდ საჭირო ნაწილს ანახლებს
// 🎨 ნახაზი (სქემა)
// User Action (კლიკი, მონაცემის შეცვლა)
//               ↓
//         React Component
//               ↓
//          Virtual DOM (ახალი)
//               ↓
//      🔍 შედარება ძველთან (Diffing)
//               ↓
//   იცვლება მხოლოდ საჭირო ელემენტები
//               ↓
//         Real DOM Update
//               ↓
//             Screen
// 📌 მარტივი მაგალითი

// ❌ ჩვეულებრივ DOM-ში:

// ერთ პატარა ცვლილებაზე შეიძლება მთელი გვერდი განახლდეს

// ✅ Virtual DOM-ში:

// იცვლება მხოლოდ ერთი ელემენტი (მაგ: ერთი <p>)
// 🔥 ჩემი სიტყვებით:

// Virtual DOM არის „შუალედური ჭკვიანი სისტემა“, რომელიც:

// ამოწმებს რა შეიცვალა
// ამცირებს ზედმეტ მუშაობას
// აჩქარებს საიტს 🚀
// 🧾 მოკლე დასკვნა:
// Virtual DOM = რეალური DOM-ის ასლი
// ადარებს ცვლილებებს
// აახლებს მხოლოდ საჭირო ნაწილს

const name = "ლუკა";
const imgUrl = "https://via.placeholder.com/150";

const myElement = (
  <div className="container">
    <h2>{name}</h2> {/* ტექსტად JS კოდი */}

    <img src={imgUrl} alt="profile" /> {/* self-closing + ატრიბუტად JS */}

    <p>ასაკი: {15 + 1}</p> {/* JS გამოთვლა ტექსტში */}

    <br /> {/* self-closing tag */}
  </div>
);

// 🔥 რა არის აქ გამოყენებული:
// ✅ self-closing tags → <img />, <br />
// ✅ ტექსტად JS კოდი → {name}, {15 + 1}
// ✅ ატრიბუტად JS კოდი → src={imgUrl}
// ✅ className → სწორი JSX სინტაქსი